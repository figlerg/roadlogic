import os
import csv
import json
import click
import math

@click.command()
@click.argument("parent_folder", type=click.Path(exists=True, file_okay=False))
def aggregate_monitoring_results(parent_folder: str):
    """
    Summarizes the monitoring results across all subfolders in `parent_folder`.

    Each subfolder is expected to contain a `monitoring_results.csv` file
    generated by the monitoring setup.

    Parameters
    ----------
    parent_folder : str
        Path to the folder containing multiple simulation result folders.

    Returns
    -------
    dict
        Dictionary with summary statistics: average cost, number of perfect runs,
        and percentage of perfect runs.
    """
    total_cost = 0.0
    num_runs = 0
    num_perfect = 0
    costs = list()

    for subdir in sorted(os.listdir(parent_folder)):
        if subdir.startswith('_'):
            continue

        gen_folder = os.path.join(parent_folder, subdir)
        result_path = os.path.join(gen_folder, "monitoring_results.csv")

        incomplete = False

        if not os.path.isfile(result_path):
            print(result_path,'\n')
            # raise FileNotFoundError(f"Expected monitoring_results.csv not found in {os.path.abspath(gen_folder)}")
            incomplete = True

        print(f"Aggregating: {os.path.abspath(gen_folder)}")

        if not incomplete:

            with open(result_path,mode='r', newline='') as f:
                reader = csv.DictReader(f)
                last_row = None
                for row in reader:
                    last_row = row

                fin = reader.fieldnames[-1]

                cost = float(last_row[fin])
                costs.append(cost)

                total_cost += cost
                if math.isclose(cost, 0.0, abs_tol=1e-3):
                    num_perfect += 1

        num_runs += 1 # also count incomplete runs
   

    summary = {
        'average_cost': total_cost / num_runs if num_runs else float('nan'),
        'num_positive_traces': num_perfect,
        'percent_positive_traces': (num_perfect / num_runs * 100) if num_runs else float('nan'),
        'total_runs': num_runs
    }

    # it is also good to see which traces are good/bad
        # Save lists of positive and negative traces
    positive_traces = []
    negative_traces = []
    no_monitoring_results = []

    for subdir in sorted(os.listdir(parent_folder)):
        if subdir.startswith('_') or subdir == "summary_log.json": # buggy directories, ignore
            continue


        gen_folder = os.path.join(parent_folder, subdir)
        result_path = os.path.join(gen_folder, "monitoring_results.csv")
        invariant_result_path = os.path.join(gen_folder, "invariant_monitor.csv")

        if not os.path.isfile(result_path):
            no_monitoring_results.append(subdir)
            continue

        if not os.path.isfile(result_path):
            no_monitoring_results.append(subdir)
            continue



        with open(result_path, mode='r', newline='') as f:
            reader = csv.DictReader(f)
            last_row = None
            for row in reader:
                last_row = row

            fin = reader.fieldnames[-1]
            cost = float(last_row[fin])

            if math.isclose(cost, 0.0, abs_tol=1e-3):
                positive_traces.append(subdir)
            else:
                negative_traces.append(subdir)

    # summary['traces'] = sorted(os.listdir(parent_folder))  # just to fix the order
    summary['positive traces'] = sorted(positive_traces)
    summary['negative traces'] = sorted(negative_traces)
    summary['no monitoring results'] = sorted(no_monitoring_results)
    summary['costs'] = dict(zip(sorted([x for x in os.listdir(parent_folder) if x[0]!='_']),costs))

    with open(os.path.join(parent_folder, "summary_log.json"), "w") as f:
        json.dump(summary, f, indent=2)


    return summary



if __name__ == '__main__':
    aggregate_monitoring_results()
